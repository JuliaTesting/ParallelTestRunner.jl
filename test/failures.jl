@testset "failing test" begin
    testsuite = Dict(
        "failing test" => quote
            println("This test will fail")
            @test 1 == 2
        end
    )
    error_line = @__LINE__() - 3

    io = IOBuffer()
    ioc = IOContext(io, :color => true)
    @test_throws Test.FallbackTestSetException("Test run finished with errors") begin
        runtests(ParallelTestRunner, ["--verbose"]; testsuite, stdout=ioc, stderr=ioc)
    end

    str = String(take!(io))
    @test contains(str, r"failing test.+ failed at")
    @test contains(str, "$(basename(@__FILE__)):$error_line")
    @test contains(str, "FAILURE")
    @test contains(str, "Output generated during execution of '\e[31mfailing test\e[39m':")
    @test contains(str, "Test Failed")
    @test contains(str, "1 == 2")
end

@testset "failed test row printed entirely to stderr" begin
    testsuite = Dict(
        "failing test" => quote
            @test 1 == 2
        end
    )

    # use separate streams: the whole row of a failed test must go to stderr
    out = IOBuffer()
    err = IOBuffer()
    @test_throws Test.FallbackTestSetException("Test run finished with errors") begin
        runtests(ParallelTestRunner, ["--verbose"]; testsuite, stdout=out, stderr=err)
    end

    outs = String(take!(out))
    errs = String(take!(err))
    m = match(r"failing test[^\n]*failed at", errs)
    @test m !== nothing
    # in verbose mode the row has three cell separators (time, init time) on
    # stderr; the init-time cell used to leak to stdout instead
    @test m !== nothing && count("│", m.match) == 3
    @test !contains(outs, "failed at")
end

@testset "nested failure" begin
    testsuite = Dict(
        "nested" => quote
            @test true
            @testset "foo" begin
                @test true
                @testset "bar" begin
                    @test false
                end
            end
        end
    )
    error_line = @__LINE__() - 5

    io = IOBuffer()
    @test_throws Test.FallbackTestSetException("Test run finished with errors") begin
        runtests(ParallelTestRunner, ["--verbose"]; testsuite, stdout=io, stderr=io)
    end

    str = String(take!(io))
    @test contains(str, r"nested .+ started at")
    @test contains(str, r"nested .+ failed at")
    @test contains(str, r"nested .+ \| .+ 2 .+ 1 .+ 3")
    @test contains(str, r"foo .+ \| .+ 1 .+ 1 .+ 2")
    @test contains(str, r"bar .+ \| .+ 1 .+ 1")
    @test contains(str, "FAILURE")
    @test contains(str, "Error in testset bar")
    @test contains(str, "$(basename(@__FILE__)):$error_line")
end

